import java.util.Locale

/**
 * The native copy in the page's language. The page tells its resolved language through the plugin method setLanguage
 * (SharedPreferences `omp.lang`); [load] reads it, and without it the system rule decides: ru / uk / be / kk -> Russian,
 * anything else -> English. Keys mirror the TS dictionaries (src/i18n); the Cloudflare texts are identical to them
 * (the page matches by code first, and by these exact strings as a fallback). Placeholders are {name}.
 */
object I18n {
    @Volatile
    var lang: String = "ru"

    private const val PREFS = "omp-native"
    private const val KEY = "omp.lang"
    private val RU_SYSTEM = setOf("ru", "uk", "be", "kk")

    /** The language from the stored value (ru | en) or, when it is missing or odd, from the system language code. */
    fun resolve(stored: String?, systemLang: String): String =
        if (stored == "ru" || stored == "en") stored else if (systemLang in RU_SYSTEM) "ru" else "en"

    /** Reads the page's language (or the system rule) into [lang]; call it at every native entry point with a context. */
    fun load(ctx: Context) {
        val stored = try {
            ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString(KEY, null)
        } catch (e: RuntimeException) {
            null
        }
        lang = resolve(stored, Locale.getDefault().language)
    }

    /** The text for [key] in [lang] with {name} placeholders filled from [args]; an unknown key returns the key. */
    fun s(key: String, vararg args: Pair<String, String>): String {
        var text = (if (lang == "en") EN else RU)[key] ?: return key
        for ((name, value) in args) text = text.replace("{" + name + "}", value)
        return text
    }

    /** The keys of one dictionary (tests compare both). */
    fun keys(language: String): Set<String> = (if (language == "en") EN else RU).keys

